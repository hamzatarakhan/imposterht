export const getAllWords = (): string[] => {
  return Object.values(words).flat();
};

export const getWordsByCategory = (category: Category): string[] => {
  if (category === 'random') {
    return getAllWords();
  }
  if (category === 'custom') {
    return [];
  }
  return words[category];
};

export const getRandomWord = (category: Category, usedWords: string[] = []): string => {
  const availableWords = getWordsByCategory(category).filter(w => !usedWords.includes(w));
  if (availableWords.length === 0) {
    // If all words used, reset
    const allWords = getWordsByCategory(category);
    return allWords[Math.floor(Math.random() * allWords.length)];
  }
  return availableWords[Math.floor(Math.random() * availableWords.length)];
};
