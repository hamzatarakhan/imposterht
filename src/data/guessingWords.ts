export const getGuessingAllWords = (): string[] => {
  return Object.values(guessingWords).flat();
};

export const getGuessingWordsByCategory = (category: GuessingCategory): string[] => {
  if (category === 'random') return getGuessingAllWords();
  return guessingWords[category];
};

export const getGuessingRandomWord = (category: GuessingCategory | GuessingCategory[], usedWords: string[] = []): string => {
  let allAvailable: string[] = [];
  const cats = Array.isArray(category) ? category : [category];

  for (const cat of cats) {
    allAvailable = [...allAvailable, ...getGuessingWordsByCategory(cat)];
  }
  allAvailable = [...new Set(allAvailable)];

  const available = allAvailable.filter(w => !usedWords.includes(w));
  if (available.length === 0) {
    return allAvailable[Math.floor(Math.random() * allAvailable.length)];
  }
  return available[Math.floor(Math.random() * available.length)];
};
